"""Regenerate constraints.txt: the exact versions the deployed server runs with.

Run it with the Python of the deployed image (3.13, linux x86_64), from the repository root:

    python3.13 scripts/update_constraints.py

It installs `.[vault,companies,rag]` into a throwaway venv, freezes it, and writes every distribution
except this package and the git dependencies (those are pinned by commit in pyproject.toml, and pip
refuses URLs in a constraints file) to constraints.txt. This package and the git dependencies are built
from source at every install, in isolated build environments that `-c` does not reach: their
`[build-system] requires` (read from pyproject.toml here and, for each git dependency, at its pinned
commit) are resolved in a second throwaway venv and frozen to build-constraints.txt, which the image and
the `install` service pass with `--build-constraint`. The CI job `locked` installs with `-c constraints.txt` and fails if
a dependency of the server is missing from the file or pinned to another version
(`scripts/check_constraints.py`).
"""
from __future__ import annotations

import platform
import re
import subprocess
import sys
import tempfile
import tomllib
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXTRAS = "vault,companies,rag"
# Installed by venv/pip themselves, not by the server's requirements.
TOOLING = {"pip", "setuptools", "wheel"}
HEADER = """\
# Exact versions of every PyPI dependency of myopenfund-mcp[{extras}], as the deployed image runs it
# (Python {py}, {plat}). Install with: pip install -c constraints.txt ".[...]"
# Generated by scripts/update_constraints.py: do not edit by hand. Git dependencies (vault-query,
# my-open-data, company-corpus, rag-engine) are pinned by commit in pyproject.toml and are not listed.
"""


BUILD_HEADER = """\
# Exact versions of the build backends of myopenfund-mcp and of its git dependencies, which pip builds
# from source at every install (Python {py}, {plat}). Install with: pip install --build-constraint
# build-constraints.txt ... Generated by scripts/update_constraints.py: do not edit by hand.
# Built from these git dependency pins (a pin bump without regenerating fails tests/test_pinning.py):
{sources}
"""
#: Build requirements no pyproject declares: hatchling asks for `editables` when it builds an
#: editable install (the CI's `pip install -e`), so it is pinned with the backends.
EXTRA_BUILD_REQUIRES = ("editables",)
GIT_DEP = re.compile(r"git\+https://github\.com/([^/@\s]+/[^/@\s]+)@([0-9a-f]{40})(?:#subdirectory=([^\s\"']+))?")


def build_requires() -> list[str]:
    """`[build-system] requires` of this package and of every git dependency at its pinned commit."""
    text = (ROOT / "pyproject.toml").read_text()
    reqs = list(tomllib.loads(text)["build-system"]["requires"])
    for repo, commit, sub in sorted(set(GIT_DEP.findall(text))):
        path = f"{sub}/pyproject.toml" if sub else "pyproject.toml"
        url = f"https://raw.githubusercontent.com/{repo}/{commit}/{path}"
        with urllib.request.urlopen(url, timeout=30) as resp:
            reqs += tomllib.loads(resp.read().decode())["build-system"]["requires"]
    return sorted(set(reqs) | set(EXTRA_BUILD_REQUIRES))


def git_pins() -> list[str]:
    """`<repo>@<commit>[#<subdirectory>]` for every git dependency of pyproject.toml, sorted."""
    text = (ROOT / "pyproject.toml").read_text()
    return sorted(f"{r}@{c}" + (f"#{sub}" if sub else "") for r, c, sub in set(GIT_DEP.findall(text)))


def freeze(venv: Path, requirements: list[str]) -> list[str]:
    subprocess.run([sys.executable, "-m", "venv", str(venv)], check=True)
    py = str(venv / "bin" / "python")
    subprocess.run([py, "-m", "pip", "install", "-q", *requirements], check=True)
    frozen = subprocess.run([py, "-m", "pip", "freeze", "--all"], check=True, capture_output=True,
                            text=True).stdout.splitlines()
    return [line for line in frozen if " @ " not in line and "==" in line]


def main() -> int:
    if sys.version_info[:2] != (3, 13) or sys.platform != "linux" or platform.machine() != "x86_64":
        print("run this with Python 3.13 on linux x86_64 (the deployed image)", file=sys.stderr)
        return 2
    with tempfile.TemporaryDirectory() as tmp:
        frozen = freeze(Path(tmp) / "run", [f"{ROOT}[{EXTRAS}]"])
        backends = build_requires()
        built = freeze(Path(tmp) / "build", backends)
    by_name = lambda line: line.split("==")[0].lower()
    pins = sorted((line for line in frozen if by_name(line) not in TOOLING), key=by_name)
    # pip itself is never a build requirement; setuptools/wheel are kept when a backend needs them.
    build_pins = sorted((line for line in built if by_name(line) != "pip"), key=by_name)
    py = ".".join(map(str, sys.version_info[:3]))
    text = HEADER.format(extras=EXTRAS, py=py, plat=f"{sys.platform} {platform.machine()}") + "\n".join(pins) + "\n"
    (ROOT / "constraints.txt").write_text(text)
    plat = f"{sys.platform} {platform.machine()}"
    (ROOT / "build-constraints.txt").write_text(BUILD_HEADER.format(py=py, plat=plat, sources="\n".join(f"#   {pin}" for pin in git_pins())) + "\n".join(build_pins) + "\n")
    print(f"constraints.txt: {len(pins)} pins; build-constraints.txt: {len(build_pins)} pins ({', '.join(backends)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
