"""A small local model on the no-vault scenario: 2 companies x 2 fiscal years, quote and cite.

Question: "For Microsoft and Alphabet, what were capital expenditures in FY2023 and FY2024, and what
does each company's annual report say about financing them? Quote and cite."

The server runs in memory over a fake SEC (no network): `FakeLive` answers `companies_resolve` and
`companies_facts` with synthetic capex facts for MSFT and an Alphabet-like issuer (FY2023, FY2024),
and the real `FilingsIndexer` (FakeEmbedder, no model download) holds four synthetic 10-Ks, fetched
and indexed before the model is asked: the test measures the model and the tool descriptions.

A run passes when (a) the final answer contains the FY2024 capex value of both companies, equal to the
rows the tools returned (formatting-tolerant: billions or millions, commas, rounding within REL_TOL),
and (b) it quotes a passage (QUOTE_WORDS words in a row) of a `companies_search_filings` hit and gives
that hit's `url`. The scenario runs RUNS times; the criterion is at least REQUIRED passes (4 of 6).

Opt-in: marker `llm`, needs a running Ollama. The model comes from MOF_MCP_IT_OLLAMA_MODEL (default
qwen3:4b). If the 4B model fails the criterion, the documented default test model is the smallest one
that passes (decision 2026-11-24): set the new default in DEFAULT_MODEL below and in the README.

    MOF_MCP_IT_OLLAMA_URL=http://127.0.0.1:11434 MOF_MCP_IT_OLLAMA_MODEL=qwen3:4b \
        pytest -m llm tests/llm/test_scenario_small_model.py -s

Everything else in this file runs by default, offline: the normaliser, the pass criterion and a scripted
session that plays a well-behaved model through the same server, so the opt-in test cannot rot.
"""
from __future__ import annotations

import datetime as dt
import os
import re
import time
from collections.abc import Iterable

import anyio
import llm_smoke  # sibling module: pytest puts this directory on sys.path
import pytest
from company_corpus.live.documents import FilingDocument, find_sections
from company_corpus.live.filings import FilingRef
from fastmcp import Client
from source_fakes import MSFT, FakeLive, entity

from myopenfund_mcp.config import Settings
from myopenfund_mcp.server import build_server

DEFAULT_MODEL = "qwen3:4b"  # the smallest model that passes the criterion (to update after a run)
RUNS = 6
REQUIRED = 4
MAX_ROUNDS = 8
REL_TOL = 0.005  # a model may round $44,477 million to "$44.5 billion": 0.5% is accepted
QUOTE_WORDS = 6  # a quotation: this many words in a row copied from a search hit
QUESTION = ("For Microsoft and Alphabet, what were capital expenditures in FY2023 and FY2024, and what "
            "does each company's annual report say about financing them? Quote and cite.")
OLLAMA_URL = os.environ.get("MOF_MCP_IT_OLLAMA_URL")

GOOGL = "0001652044"
CAPEX_TAG = "us-gaap:PaymentsToAcquirePropertyPlantAndEquipment"
#: cik -> {fiscal year end: capex in USD}. Synthetic issuer for Alphabet: its figures are the fixture.
CAPEX = {
    MSFT: {dt.date(2023, 6, 30): 28_107_000_000, dt.date(2024, 6, 30): 44_477_000_000},
    GOOGL: {dt.date(2023, 12, 31): 32_251_000_000, dt.date(2024, 12, 31): 52_535_000_000},
}
FY24_END = {MSFT: dt.date(2024, 6, 30), GOOGL: dt.date(2024, 12, 31)}
FINANCING = {
    MSFT: "We fund our capital expenditures for datacenters from cash generated by operations and from "
          "our cash and short-term investments, and we have no plan to issue debt to finance them.",
    GOOGL: "We finance our capital expenditures for technical infrastructure through cash flows from "
           "operating activities and cash and marketable securities, and we may also borrow when needed.",
}
NAMES = {MSFT: "Microsoft", GOOGL: "Alphabet"}


# --- normaliser and pass criterion (pure) -------------------------------------------------------------

_UNITS = {"trillion": 1e12, "billion": 1e9, "bn": 1e9, "b": 1e9, "million": 1e6, "mm": 1e6, "m": 1e6,
          "thousand": 1e3, "k": 1e3}
_AMOUNT = re.compile(r"(?<![\w.,])(\d{1,3}(?:,\d{3})+(?:\.\d+)?|\d+(?:\.\d+)?)(?:\s*(trillion|billion|bn|million|mm|thousand|[bmk])\b)?",
                     re.IGNORECASE)
_DATE_WORDS = re.compile(r"\b(?:fy|fiscal|year|q[1-4])\s*['’]?\d{2,4}\b", re.IGNORECASE)


def amounts(text: str) -> set[float]:
    """Every number of `text` as USD: '$44.5 billion', '44,477 million', '44477000000' all give a
    value. A number with no unit counts as dollars and, too, as millions (a table's 'in millions')."""
    found: set[float] = set()
    for match in _AMOUNT.finditer(_DATE_WORDS.sub(" ", text)):
        number, unit = float(match.group(1).replace(",", "")), match.group(2)
        if unit:
            found.add(number * _UNITS[unit.lower()])
        else:
            found.update((number, number * 1e6))
    return found


def contains_amount(text: str, value: float, *, rel_tol: float = REL_TOL) -> bool:
    return any(abs(found - value) <= rel_tol * abs(value) for found in amounts(text))


def fy2024_rows(results: Iterable[tuple[str, dict, object]]) -> dict[str, float]:
    """cik -> FY2024 capex, from the `companies_facts` rows the model was given (annual, capex tag)."""
    values: dict[str, float] = {}
    for name, _args, content in results:
        if name != "companies_facts" or not isinstance(content, dict):
            continue
        for row in content.get("rows") or []:
            if (row.get("original_tag") == CAPEX_TAG and row.get("frequency") == "annual"
                    and str(row.get("valid_date", ""))[:4] == "2024" and row.get("entity_value", row.get("cik"))):
                values[row.get("cik") or row["entity_value"]] = row["value"]
    return values


def search_hits(results: Iterable[tuple[str, dict, object]]) -> list[dict]:
    return [hit for name, _args, content in results if name == "companies_search_filings"
            and isinstance(content, dict) for hit in content.get("hits") or []]


def _words(text: str) -> list[str]:
    return re.findall(r"[\w$%.,'-]+", text.lower())


def quotes_a_hit(answer: str, hits: list[dict], *, words: int = QUOTE_WORDS) -> bool:
    """The answer copies `words` words in a row from a hit AND gives that hit's url."""
    said = " " + " ".join(_words(answer)) + " "
    for hit in hits:
        if not hit.get("url") or hit["url"] not in answer:
            continue
        text = _words(hit.get("text") or "")
        if any(" " + " ".join(text[i:i + words]) + " " in said for i in range(len(text) - words + 1)):
            return True
    return False


def scenario_passed(results: list[tuple[str, dict, object]], answer: str) -> tuple[bool, str]:
    """(pass, why not). `results`: (tool, arguments, structured result) in call order."""
    given = fy2024_rows(results)
    missing = sorted({MSFT, GOOGL} - set(given))
    if missing:
        return False, f"no FY2024 capex row from companies_facts for {missing}"
    absent = [NAMES[c] for c in (MSFT, GOOGL) if not contains_amount(answer, given[c])]
    if absent:
        return False, f"answer lacks the FY2024 capex of {absent}"
    if not quotes_a_hit(answer, search_hits(results)):
        return False, "no quoted passage with the url of a companies_search_filings hit"
    return True, ""


# --- the offline server -------------------------------------------------------------------------------


class CapexLive(FakeLive):
    """FakeLive that serves capex facts for MSFT and the Alphabet-like issuer."""

    def entities(self) -> list[dict]:
        return [*super().entities(), entity(GOOGL, "Alphabet Inc.", "GOOGL")]

    def read(self, dataset, *, as_of, filters, columns, limit, vintages=False, budget_s=None) -> list[dict]:
        cik = filters["entity_value"][0]
        self._enter(f"read:{dataset}", cik)
        tags = filters.get("original_tag")
        if tags and CAPEX_TAG not in tags:
            return []
        known = dt.datetime(2024, 7, 30, tzinfo=dt.UTC)
        return [{"entity_scheme": "cik", "entity_value": cik, "original_tag": CAPEX_TAG,
                 "frequency": "annual", "valid_date": end, "value": value, "unit": "USD",
                 "filing_ref": f"{cik}-{end.year}", "known_at": known, "batch_id": "b1"}
                for end, value in CAPEX.get(cik, {}).items()]


def filing_ref(cik: str, year: int) -> FilingRef:
    end = FY24_END[cik].replace(year=year)
    accession = f"{int(cik):010d}-{year % 100:02d}-000001"
    return FilingRef(cik=cik, accession=accession, form="10-K", report_date=end,
                     filed=end + dt.timedelta(days=30), accepted=None, primary_document="annual.htm",
                     url=f"https://www.sec.gov/Archives/edgar/data/{int(cik)}/{accession.replace('-', '')}",
                     doc_id=f"sec-{accession}")


REFS = {cik: [filing_ref(cik, 2024), filing_ref(cik, 2023)] for cik in (MSFT, GOOGL)}


def annual_report(ref: FilingRef) -> str:
    name, year = NAMES[ref.cik], ref.report_date.year
    paid = CAPEX[ref.cik][ref.report_date] / 1e6
    return (f"# {name.upper()} ANNUAL REPORT ON FORM 10-K\n\nFor the fiscal year ended {ref.report_date:%B %d, %Y}.\n\n"
            f"## PART I\n\n## Item 1. Business\n\n{name} builds software, cloud and advertising products "
            f"for consumers and enterprises around the world.\n\n## PART II\n\n"
            f"## Item 7. Management's Discussion and Analysis\n\n"
            f"Cash used for additions to property and equipment was ${paid:,.0f} million in fiscal year {year}. "
            f"{FINANCING[ref.cik]}\n\n"
            f"## Item 8. Financial Statements and Supplementary Data\n\n"
            f"Payments for property and equipment: {paid:,.0f} in millions of dollars.\n")


def load(ref: FilingRef, sec) -> FilingDocument:
    markdown = annual_report(ref)
    return FilingDocument(ref=ref, markdown=markdown, sections=find_sections(markdown, ref.form))


class Recording:
    """A Client stand-in that keeps every tool result (name, arguments, structured content)."""

    def __init__(self, client: Client):
        self.client, self.results = client, []

    async def list_tools(self):
        return await self.client.list_tools()

    async def call_tool(self, name, args, **kw):
        result = await self.client.call_tool(name, args, **kw)
        content = result.structured_content
        self.results.append((name, args, content if content is not None else
                             "\n".join(getattr(b, "text", "") for b in result.content)))
        return result


async def warm_server(tmp_path):
    """(indexer, make_client): four 10-Ks fetched and indexed already. Close the indexer when done."""
    from rag_engine.embedding import FakeEmbedder
    from test_filings_indexer import SPEC, WordTokenizer

    from myopenfund_mcp.filings.indexer import FilingsIndexer

    settings = Settings(sec_contact="someone@example.invalid", cache_dir=str(tmp_path / "cache"),
                        chunk_max_tokens=60, chunk_overlap_tokens=8)
    embedder = FakeEmbedder(SPEC)
    indexer = FilingsIndexer(settings, sec=object(), embedder_factory=lambda: embedder,
                             tokenizer_factory=WordTokenizer, document_loader=load)
    live = CapexLive(refs=REFS)

    def make_client() -> Client:
        return Client(build_server(settings, companies_live=live, filings_indexer=indexer))

    async with make_client() as warm:
        fetched = (await warm.call_tool("companies_fetch_filings", {"companies": ["MSFT", "GOOGL"]})).data
        assert fetched["total"] == 4, fetched
        deadline = time.monotonic() + 60
        while any(s.state != "ready" for s in indexer.status()):
            assert time.monotonic() < deadline, "not indexed in time"
            await anyio.sleep(0.02)
    return indexer, make_client


async def run_once(make_client, chat) -> tuple[bool, str, list[tuple[str, dict]], str]:
    async with make_client() as client:
        recorder = Recording(client)
        calls, answer = await llm_smoke.run_session(recorder, chat, QUESTION, max_rounds=MAX_ROUNDS)
    ok, why = scenario_passed(recorder.results, answer)
    return ok, why, calls, answer


# --- offline tests (default suite) --------------------------------------------------------------------


@pytest.mark.parametrize("text", [
    "$44.477 billion", "44,477 million", "USD 44477 million", "44477000000", "$44,477,000,000",
    "about $44.5 billion", "44.5bn", "44,477.0 M", "capex was 44,477 (in millions)",
])
def test_normaliser_reads_msft_fy2024_in_any_format(text):
    assert contains_amount(text, 44_477_000_000)


@pytest.mark.parametrize("text", [
    "$44.0 billion", "$45 billion", "44.477 million", "28,107 million", "FY2024 Q4 2024", "no figure",
    "$4.4477 billion",
])
def test_normaliser_rejects_other_values(text):
    assert not contains_amount(text, 44_477_000_000)


def test_normaliser_ignores_years_and_fiscal_labels():
    assert 2024.0 not in amounts("FY2024 and fiscal year 2024 and Q3 2024")
    assert 52_535_000_000 in amounts("Alphabet: $52.535 billion, up from $32.3 billion")


def row(cik, end, value, tag=CAPEX_TAG, frequency="annual"):
    return {"cik": cik, "original_tag": tag, "frequency": frequency, "valid_date": end, "value": value}


HIT = {"text": "We fund our capital expenditures for datacenters from cash generated by operations",
       "url": "https://www.sec.gov/Archives/edgar/data/1/a"}
GOOD_RESULTS = [
    ("companies_facts", {}, {"rows": [row(MSFT, "2024-06-30", 44_477_000_000), row(MSFT, "2023-06-30", 28_107_000_000),
                                      row(GOOGL, "2024-12-31", 52_535_000_000)]}),
    ("companies_search_filings", {}, {"hits": [HIT]}),
]
GOOD_ANSWER = ("Microsoft spent $44.5 billion in FY2024, Alphabet $52.5 billion. Microsoft: \"We fund our capital "
               "expenditures for datacenters from cash generated by operations\" (https://www.sec.gov/Archives/edgar/data/1/a).")


def test_fy2024_rows_takes_annual_capex_rows_of_2024_only():
    rows = fy2024_rows([*GOOD_RESULTS, ("companies_facts", {}, {"rows": [row(MSFT, "2024-06-30", 1, frequency="quarterly"),
                                                                       row(MSFT, "2024-06-30", 2, tag="us-gaap:Revenues")]})])
    assert rows == {MSFT: 44_477_000_000, GOOGL: 52_535_000_000}


def test_criterion_passes_a_good_answer():
    assert scenario_passed(GOOD_RESULTS, GOOD_ANSWER) == (True, "")


@pytest.mark.parametrize(("results", "answer", "needle"), [
    (GOOD_RESULTS[1:], GOOD_ANSWER, "no FY2024 capex row"),  # never called companies_facts
    (GOOD_RESULTS, GOOD_ANSWER.replace("$52.5 billion", "$50 billion"), "Alphabet"),
    (GOOD_RESULTS, GOOD_ANSWER.replace("$44.5 billion", "$28.1 billion"), "Microsoft"),
    (GOOD_RESULTS, GOOD_ANSWER.replace("(https://www.sec.gov/Archives/edgar/data/1/a)", ""), "quoted passage"),
    (GOOD_RESULTS, GOOD_ANSWER.replace("capital expenditures for datacenters from cash", "capex on datacenters out of cash"), "quoted passage"),
    (GOOD_RESULTS, GOOD_ANSWER.replace("/data/1/a", "/data/9/z"), "quoted passage"),  # a url nobody returned
])
def test_criterion_fails(results, answer, needle):
    ok, why = scenario_passed(results, answer)
    assert not ok and needle in why


@pytest.mark.anyio
async def test_scripted_good_model_passes_on_the_offline_server(tmp_path):
    """Plays a well-behaved model against the real tools: the fixtures, the tools and the criterion agree."""
    indexer, make_client = await warm_server(tmp_path)
    try:
        async with make_client() as client:
            facts = (await client.call_tool("companies_facts", {"companies": ["MSFT", "GOOGL"], "tags": [CAPEX_TAG]})).data
        assert facts["total"] == 4 and {r["cik"] for r in facts["rows"]} == {MSFT, GOOGL}
        urls = []

        class Chat:
            def __init__(self):
                self.step = 0

            def __call__(self, messages, tools):
                self.step += 1
                if self.step == 1:
                    return {"role": "assistant", "content": "", "tool_calls": [{"function": {
                        "name": "companies_facts", "arguments": {"companies": ["MSFT", "GOOGL"], "tags": [CAPEX_TAG]}}}]}
                if self.step == 2:
                    return {"role": "assistant", "content": "", "tool_calls": [{"function": {
                        "name": "companies_search_filings", "arguments": {
                            "query": "financing capital expenditures", "companies": ["MSFT", "GOOGL"], "limit": 8}}}]}
                tool_text = [m["content"] for m in messages if m["role"] == "tool"]
                assert len(tool_text) == 2
                import json
                hits = json.loads(tool_text[1])["hits"]
                urls.extend(h["url"] for h in hits)
                best = next(h for h in hits if "capital expenditures" in h["text"])
                words = best["text"].split()[:12]
                return {"role": "assistant", "content": (
                    "Microsoft FY2024: $44.477 billion (FY2023 $28.107 billion). Alphabet FY2024: 52,535 million "
                    f"(FY2023 $32.251 billion). \"{' '.join(words)}\" {best['url']}")}

        ok, why, calls, answer = await run_once(make_client, Chat())
    finally:
        indexer.close()
    assert ok, (why, calls, answer)
    assert [c[0] for c in calls] == ["companies_facts", "companies_search_filings"] and urls


# --- the opt-in scenario ------------------------------------------------------------------------------


@pytest.mark.llm
@pytest.mark.anyio
@pytest.mark.skipif(not OLLAMA_URL, reason="MOF_MCP_IT_OLLAMA_URL not set")
async def test_small_model_scenario(tmp_path):
    model = os.environ.get("MOF_MCP_IT_OLLAMA_MODEL") or DEFAULT_MODEL
    chat = llm_smoke.ollama_chat(OLLAMA_URL, model)
    indexer, make_client = await warm_server(tmp_path)
    passes, report = 0, []
    try:
        for n in range(1, RUNS + 1):
            ok, why, calls, answer = await run_once(make_client, chat)
            passes += ok
            report.append(f"run {n}: {'PASS' if ok else 'FAIL'} rounds={len(calls)} "
                          f"tools={[c[0] for c in calls]} {why}\n  answer: {answer[:600]!r}")
            print(report[-1])
    finally:
        indexer.close()
    print(f"{model}: {passes}/{RUNS} (criterion >= {REQUIRED})")
    assert passes >= REQUIRED, f"{model}: {passes}/{RUNS} < {REQUIRED}\n" + "\n".join(report)
